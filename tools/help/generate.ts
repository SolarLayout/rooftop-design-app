// The topics of content/help read and the typed manifest written (bun help:gen). Node only: never reached from the app.
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";
import { parse } from "yaml";
import { keyFromPath } from "../../apps/web/lib/help/keys";
import { frontmatterOf, type Frontmatter } from "./frontmatter";
import type { Option } from "./options";

export const CONTENT_DIR = resolve(import.meta.dir, "../../apps/web/content/help");
export const MANIFEST_PATH = resolve(import.meta.dir, "../../apps/web/lib/help/manifest.gen.ts");

export type Topic = { key: string; path: string; frontmatter: Frontmatter; body: string };

const FRONTMATTER = /^---\n([\s\S]*?)\n---\n?/;

function filesUnder(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? filesUnder(full) : [full];
  });
}

/** One topic of its text, or what is wrong with it, with its path. */
export function topicOf(path: string, text: string): Topic {
  const key = keyFromPath(path);
  const found = FRONTMATTER.exec(text);
  if (!found || found[1] === undefined) throw new Error(`${path}: no frontmatter (--- … ---) at the top`);
  let fields: unknown;
  try {
    fields = parse(found[1]);
  } catch (error) {
    throw new Error(`${path}: the frontmatter is not YAML (quote a line with a colon in it): ${error instanceof Error ? error.message.split("\n")[0] : String(error)}`);
  }
  const read = frontmatterOf(fields);
  if (!read.ok) throw new Error(`${path}: ${read.problems.join("; ")}`);
  if (read.frontmatter.kind !== key.split(".")[1]) throw new Error(`${path}: kind "${read.frontmatter.kind}" is not the key's, "${key.split(".")[1]}"`);
  return { key, path, frontmatter: read.frontmatter, body: text.slice(found[0].length) };
}

/** Every topic under `dir`, by key; a file of another kind there is refused. */
export function readTopics(dir: string = CONTENT_DIR): Topic[] {
  return filesUnder(dir)
    .map((file) => {
      const path = relative(dir, file).split(sep).join("/");
      return topicOf(path, readFileSync(file, "utf8"));
    })
    .sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

const json = (value: unknown) => JSON.stringify(value);

/** The manifest: every key a type, each topic's metadata, its options labelled as the code labels them, its body loaded when opened. */
export function manifestOf(topics: readonly Topic[], optionsOf: (key: string) => readonly Option[] | undefined): string {
  const entries = topics.map(({ key, path, frontmatter }) => {
    const { title, summary, kind, values, related, aliases } = frontmatter;
    const labels = new Map((optionsOf(key) ?? []).map((option) => [option.id, option.label]));
    const labelled = values && Object.fromEntries(Object.entries(values).map(([id, meaning]) => [id, { label: labels.get(id) ?? id, meaning }]));
    return [
      `  ${json(key)}: {`,
      `    title: ${json(title)},`,
      `    summary: ${json(summary)},`,
      `    kind: ${json(kind)},`,
      ...(labelled ? [`    values: ${json(labelled)},`] : []),
      `    related: ${json(related)},`,
      `    aliases: ${json(aliases)},`,
      `    load: () => import(${json(`../../content/help/${path}`)}),`,
      "  },",
    ].join("\n");
  });
  const aliases = topics.flatMap(({ key, frontmatter }) => frontmatter.aliases.map((alias) => `  ${json(alias)}: ${json(key)},`));
  return [
    "// GENERATED by `bun help:gen` from apps/web/content/help. Do not edit: write the topic and run it again.",
    'import type { HelpEntry } from "./types";',
    "",
    `export const HELP_KEYS = [${topics.map(({ key }) => `\n  ${json(key)},`).join("")}${topics.length ? "\n" : ""}] as const;`,
    "",
    "export type HelpKey = (typeof HELP_KEYS)[number];",
    "",
    `export const MANIFEST: Record<HelpKey, HelpEntry> = {${entries.length ? `\n${entries.join("\n")}\n` : ""}};`,
    "",
    `export const ALIASES: Record<string, HelpKey> = {${aliases.length ? `\n${aliases.join("\n")}\n` : ""}};`,
    "",
  ].join("\n");
}
