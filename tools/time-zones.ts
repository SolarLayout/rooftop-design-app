// Writes the table of time zones and their countries (apps/web/lib/country/time-zones.gen.ts) from the tz database's
// zone.tab, the fallback of the user's country when the request does not carry it (plan/phase-16-plan.md, step 2).
// Usage: bun tools/time-zones.ts [/usr/share/zoneinfo]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { nodeMissingMessage, resolveNode } from "./lib/node";

const OUT = "apps/web/lib/country/time-zones.gen.ts";

/**
 * Each zone of zone.tab and its country, under its own name and under the name a browser gives it (ICU keeps some
 * old names: Asia/Kolkata is reported as Asia/Calcutta), sorted by zone.
 */
export function timeZoneTable(zoneTab: string, browserNameOf: (zone: string) => string): [string, string][] {
  const table = new Map<string, string>();
  for (const line of zoneTab.split("\n")) {
    if (line.startsWith("#") || line.trim() === "") continue;
    const [country, , zone] = line.split("\t");
    if (!country || !zone) throw new Error(`zone.tab has a line without a country and a zone: "${line}"`);
    table.set(zone, country);
    table.set(browserNameOf(zone), country);
  }
  return [...table].sort(([a], [b]) => a.localeCompare(b));
}

/**
 * The names browsers give the zones, asked of Node: its ICU is the browsers' (Chrome reports Asia/Calcutta), where bun's
 * runtime gives the tz database's own names. A zone the runtime does not know keeps its name.
 */
function browserNamesOf(zones: string[]): Map<string, string> {
  const node = resolveNode();
  if (node === null) throw new Error(nodeMissingMessage());
  const script =
    "const zones = JSON.parse(process.argv[1]);" +
    "console.log(JSON.stringify(zones.map((z) => { try { return new Intl.DateTimeFormat('en', { timeZone: z }).resolvedOptions().timeZone; } catch { return z; } })));";
  const names: string[] = JSON.parse(execFileSync(node.path, ["-e", script, JSON.stringify(zones)], { encoding: "utf8" }));
  return new Map(zones.map((zone, index) => [zone, names[index] ?? zone]));
}

function source(table: [string, string][], version: string): string {
  const rows = table.map(([zone, country]) => `  ${JSON.stringify(zone)}: ${JSON.stringify(country)},`).join("\n");
  return (
    `// Generated by tools/time-zones.ts from the tz database ${version} (zone.tab, public domain). Do not edit by hand.\n` +
    `// Each time zone, under its own name and the one a browser reports, and its country (ISO 3166-1 alpha-2).\n` +
    `export const COUNTRY_OF_TIME_ZONE: Readonly<Record<string, string>> = {\n${rows}\n};\n`
  );
}

if (import.meta.main) {
  const folder = process.argv[2] ?? "/usr/share/zoneinfo";
  const version = readFileSync(join(folder, "+VERSION"), "utf8").trim();
  const zoneTab = readFileSync(join(folder, "zone.tab"), "utf8");
  const zones = timeZoneTable(zoneTab, (zone) => zone).map(([zone]) => zone);
  const browserNames = browserNamesOf(zones);
  const table = timeZoneTable(zoneTab, (zone) => browserNames.get(zone) ?? zone);
  writeFileSync(OUT, source(table, version));
  console.log(`Wrote ${OUT}: ${table.length} zones, tz ${version}.`);
}
